export const LIVE_STRINGS: Record<LiveLang, Table> = { en, hi };

export function lt(lang: LiveLang, key: LiveKey, vars?: Record<string, string | number>): string {
  let s: string = LIVE_STRINGS[lang][key] ?? en[key];
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

