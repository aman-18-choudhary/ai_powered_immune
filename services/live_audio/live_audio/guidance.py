"""Recommended safety actions: a static, reviewed list (``source: static_guidance``).

Selected by detected indicator codes and by the current level; never generated by a model.
The advice follows the public guidance of Indian authorities (1930 cyber-crime helpline,
cybercrime.gov.in; no agency conducts a "digital arrest" over a call).
"""

from __future__ import annotations

from typing import Any

ACTIONS: dict[str, str] = {
    "hang_up": "Hang up. A genuine officer or bank will not object to you ending the call and calling back on an official number.",
    "no_digital_arrest": "There is no such thing as a 'digital arrest'. Police, CBI, ED, customs or RBI do not arrest or question people over video calls.",
    "no_otp": "Never share an OTP, UPI PIN, CVV, password or card number with anyone on a call, even if they say they are from your bank.",
    "no_transfer": "Do not send money, scan a QR code or approve a collect request because a caller told you to. Receiving money never needs your PIN.",
    "no_remote_app": "Do not install AnyDesk, TeamViewer or any screen-sharing app at a caller's request. Uninstall it if you already did.",
    "tell_someone": "Talk to a family member or someone you trust right now. Callers who demand secrecy are a warning sign.",
    "verify_bank": "Call your bank yourself using the number printed on your card or passbook, not a number the caller gave you.",
    "no_links": "Do not open links or type in web addresses read out on a call.",
    "report": "If money was sent or details were shared, call 1930 (National Cyber Crime Helpline) immediately or report at cybercrime.gov.in, and inform your bank.",
}

BY_CODE: dict[str, tuple[str, ...]] = {
    "DIGITAL_ARREST_PHRASE": ("no_digital_arrest", "hang_up"),
    "AUTHORITY_IMPERSONATION": ("no_digital_arrest", "hang_up"),
    "LEGAL_THREAT": ("no_digital_arrest", "hang_up"),
    "INTIMIDATION": ("no_digital_arrest", "hang_up"),
    "ISOLATION_DEMAND": ("tell_someone",),
    "SECRECY_DEMAND": ("tell_someone",),
    "CREDENTIAL_ASK": ("no_otp",),
    "OTP_PIN_REQUEST": ("no_otp",),
    "ACCOUNT_VERIFICATION_ASK": ("no_otp", "verify_bank"),
    "SAFE_ACCOUNT_TRANSFER": ("no_transfer",),
    "PAYMENT_DEMAND": ("no_transfer",),
    "MONEY_TRANSFER_INSTRUCTION": ("no_transfer",),
    "UPI_BANK_FRAUD": ("no_transfer", "verify_bank"),
    "SPOKEN_PAYMENT_ID": ("no_transfer",),
    "REMOTE_ACCESS_REQUEST": ("no_remote_app",),
    "SPOKEN_LINK": ("no_links",),
}
ORDER = tuple(ACTIONS)


def actions_for(codes: set[str], level: str | None) -> list[dict[str, Any]]:
    if not codes:
        return []
    ids: set[str] = set()
    for c in codes:
        ids.update(BY_CODE.get(c, ()))
    if level in ("HIGH", "CRITICAL"):
        ids.update(("hang_up", "verify_bank", "report"))
    return [
        {"id": i, "text": ACTIONS[i], "source": "static_guidance", "priority": n}
        for n, i in enumerate(x for x in ORDER if x in ids)
    ]
